"""PostgreSQL snapshot and append-only events in the same transaction."""

import json
import os
import shutil
import sqlite3
import threading
from contextlib import closing, contextmanager
from datetime import datetime, timezone
from pathlib import Path
from tempfile import TemporaryDirectory

import psycopg
from psycopg import sql
from psycopg.rows import dict_row

from .workflow import initial_state


def _connect(dsn):
    if dsn is None:
        dsn = os.environ.get("DECOCTION_DATABASE_URL", "")
        if not dsn and not os.environ.get("PGDATABASE"):
            raise RuntimeError("请设置 DECOCTION_DATABASE_URL，或通过 PGDATABASE 等环境变量配置 PostgreSQL")
    return psycopg.connect(dsn, connect_timeout=5, row_factory=dict_row)


def _create_tables(db):
    # JSON preserves object key order used by the existing lists and snapshots.
    db.execute("""
        CREATE TABLE IF NOT EXISTS simulation_state (
            id INTEGER PRIMARY KEY CHECK (id = 1), payload JSON NOT NULL
        )
    """)
    db.execute("""
        CREATE TABLE IF NOT EXISTS events (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            sim_time DOUBLE PRECISION NOT NULL, real_time TEXT NOT NULL,
            type TEXT NOT NULL, entity_id TEXT NOT NULL, payload JSON NOT NULL
        )
    """)
    db.execute("CREATE INDEX IF NOT EXISTS idx_events_entity ON events(entity_id, id)")


class Store:
    def __init__(self, dsn=None):
        self.dsn = dsn
        self.lock = threading.RLock()
        self.revision = 0
        with _connect(self.dsn) as db:
            _create_tables(db)
            db.execute("INSERT INTO simulation_state VALUES (1, %s::json) ON CONFLICT (id) DO NOTHING",
                       (json.dumps(initial_state(), ensure_ascii=False, allow_nan=False),))
            self._restore_prescription_times(db)

    @staticmethod
    def _restore_prescription_times(db):
        """Recover receipt and review times from their original events, never from sim time."""
        state = db.execute("SELECT payload FROM simulation_state WHERE id=1 FOR UPDATE").fetchone()["payload"]
        targets = (
            ("prescription.created", state["prescriptions"], "created_real_time"),
            ("prescription.reviewed", {pid: p["review"] for pid, p in state["prescriptions"].items()
                                       if p.get("review")}, "real_time"),
        )
        restored = False
        for event_type, records, field in targets:
            missing = [pid for pid, record in records.items() if not record.get(field)]
            if not missing:
                continue
            rows = db.execute(
                "SELECT DISTINCT ON (entity_id) entity_id, real_time FROM events "
                "WHERE type=%s AND entity_id = ANY(%s) ORDER BY entity_id, id",
                (event_type, missing),
            ).fetchall()
            for row in rows:
                records[row["entity_id"]][field] = row["real_time"]
            restored = restored or bool(rows)
        if restored:
            db.execute("UPDATE simulation_state SET payload=%s::json WHERE id=1",
                       (json.dumps(state, ensure_ascii=False, allow_nan=False),))

    @contextmanager
    def transaction(self):
        with self.lock:
            with _connect(self.dsn) as db:
                state = db.execute("SELECT payload FROM simulation_state WHERE id=1 FOR UPDATE").fetchone()["payload"]
                if state["schema_version"] != 1:
                    raise RuntimeError("数据库版本不兼容")
                pending = []

                def emit(event_type, entity_id, **payload):
                    real_time = datetime.now(timezone.utc).isoformat()
                    pending.append((state["clock"]["now"], real_time,
                                    event_type, entity_id, json.dumps(payload, ensure_ascii=False, allow_nan=False)))
                    return real_time

                yield state, emit
                db.execute("UPDATE simulation_state SET payload=%s::json WHERE id=1",
                           (json.dumps(state, ensure_ascii=False, allow_nan=False),))
                if pending:
                    with db.cursor() as cursor:
                        cursor.executemany(
                            "INSERT INTO events(sim_time, real_time, type, entity_id, payload) "
                            "VALUES (%s, %s, %s, %s, %s::json)", pending,
                        )
            self.revision += 1

    def read(self):
        with _connect(self.dsn) as db:
            row = db.execute("""
                SELECT payload, (SELECT COALESCE(MAX(id), 0) FROM events) AS last_event_id
                FROM simulation_state WHERE id=1
            """).fetchone()
            state = row["payload"]
            state["last_event_id"] = row["last_event_id"]
            return state

    def events(self, after_id=0, limit=100, entity_id=None, event_type=None):
        query = "SELECT * FROM events WHERE id > %s"
        args = [after_id]
        if entity_id:
            query += " AND entity_id = %s"
            args.append(entity_id)
        if event_type:
            query += " AND type = %s"
            args.append(event_type)
        query += " ORDER BY id LIMIT %s"
        args.append(limit)
        with _connect(self.dsn) as db:
            return db.execute(query, args).fetchall()


def import_sqlite(path, dsn=None):
    """Import a stopped SQLite database or a consistent backup into an empty PostgreSQL database."""
    source_path = Path(path).resolve(strict=True)
    with TemporaryDirectory(prefix="decoction-import-") as temp_dir:
        # A private copy allows SQLite to rebuild the WAL index even when the source is mounted read-only.
        snapshot = Path(temp_dir) / "simulation.db"
        shutil.copyfile(source_path, snapshot)
        wal = source_path.with_name(source_path.name + "-wal")
        if wal.is_file():
            shutil.copyfile(wal, snapshot.with_name(snapshot.name + "-wal"))
        with closing(sqlite3.connect(snapshot.as_uri() + "?mode=ro", uri=True)) as source:
            source.execute("BEGIN")
            state_row = source.execute("SELECT payload FROM simulation_state WHERE id=1").fetchone()
            if state_row is None:
                raise ValueError("SQLite 源库缺少仿真快照")
            payload = state_row[0]
            state = json.loads(payload)
            if not isinstance(state, dict) or state.get("schema_version") != 1:
                raise ValueError("SQLite 源库的快照版本不兼容")
            if any(not isinstance(state.get(key), dict) for key in
                   ("clock", "prescriptions", "batches", "devices", "alarms")):
                raise ValueError("SQLite 源库的快照缺少必要字段")
            seq = source.execute("SELECT seq FROM sqlite_sequence WHERE name='events'").fetchone()
            with _connect(dsn) as db:
                _create_tables(db)
                db.execute("LOCK TABLE simulation_state, events IN ACCESS EXCLUSIVE MODE")
                if db.execute("SELECT 1 FROM simulation_state UNION ALL SELECT 1 FROM events LIMIT 1").fetchone():
                    raise ValueError("PostgreSQL 目标库已初始化，请使用尚未启动应用的空数据库")
                db.execute("INSERT INTO simulation_state VALUES (1, %s::json)", (payload,))
                rows = source.execute("SELECT id, sim_time, real_time, type, entity_id, payload FROM events ORDER BY id")
                count, last_id = 0, 0
                with db.cursor() as cursor:
                    while records := rows.fetchmany(1000):
                        cursor.executemany(
                            "INSERT INTO events(id, sim_time, real_time, type, entity_id, payload) "
                            "VALUES (%s, %s, %s, %s, %s, %s::json)", records,
                        )
                        count += len(records)
                        last_id = records[-1][0]
                next_id = max(last_id, seq[0] if seq else 0) + 1
                db.execute(sql.SQL("ALTER TABLE events ALTER COLUMN id RESTART WITH {}").format(sql.Literal(next_id)))
    return {"prescriptions": len(state["prescriptions"]), "batches": len(state["batches"]),
            "devices": len(state["devices"]), "events": count, "last_event_id": last_id}
